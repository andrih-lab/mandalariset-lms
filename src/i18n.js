export function pickLang(req) {
  const q = req.query?.lang;
  if (q === 'id' || q === 'en') return q;
  const c = req.cookies?.lang;
  return c === 'en' ? 'en' : 'id';
}

export const makeT = (lang) => (k) => D[k]?.[lang] ?? k;
